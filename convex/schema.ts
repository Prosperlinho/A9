import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
import { authTables } from "@convex-dev/auth/server";

export const rideStatus = v.union(
  v.literal("requested"),
  v.literal("negotiating"),
  v.literal("offer_made"),
  v.literal("accepted"),
  v.literal("rider_arriving"),
  v.literal("in_progress"),
  v.literal("awaiting_confirmation"),
  v.literal("completed"),
  v.literal("cancelled"),
  v.literal("disputed"),
  v.literal("expired"),
);
export const verificationStatus = v.union(
  v.literal("not_verified"),
  v.literal("under_review"),
  v.literal("approved"),
  v.literal("rejected"),
);
export const verificationDecision = v.union(
  v.literal("pass"),
  v.literal("review"),
  v.literal("fail"),
);
export const paymentStatus = v.union(
  v.literal("pending"),
  v.literal("paid"),
  v.literal("failed"),
  v.literal("cancelled"),
  v.literal("processing"),
);
export const earningsStatus = v.union(
  v.literal("pending"),
  v.literal("eligible"),
  v.literal("paid"),
  v.literal("failed"),
);
export const withdrawalStatus = v.union(
  v.literal("pending"),
  v.literal("processing"),
  v.literal("paid"),
  v.literal("failed"),
);
export const paymentStage = v.union(
  v.literal("unpaid"),
  v.literal("paid_held"),
  v.literal("awaiting_completion"),
  v.literal("eligible_for_rider"),
  v.literal("pending_payout"),
  v.literal("paid_to_rider"),
  v.literal("refunded"),
  v.literal("disputed"),
);
export const payoutStatus = v.union(
  v.literal("pending"),
  v.literal("processing"),
  v.literal("paid"),
  v.literal("failed"),
  v.literal("retry"),
  v.literal("review"),
);
export const rideRequestStatus = v.union(
  v.literal("searching"),
  v.literal("offers_available"),
  v.literal("booked"),
  v.literal("cancelled"),
  v.literal("expired"),
);
export const rideOfferStatus = v.union(
  v.literal("submitted"),
  v.literal("accepted"),
  v.literal("rejected"),
  v.literal("withdrawn"),
  v.literal("closed"),
);

export default defineSchema({
  ...authTables,
  users: defineTable({
    name: v.optional(v.string()),
    email: v.optional(v.string()),
    phone: v.optional(v.string()),
    matricNumber: v.optional(v.string()),
    faculty: v.optional(v.string()),
    department: v.optional(v.string()),
    vehicle: v.optional(v.string()),
    plateNumber: v.optional(v.string()),
    identificationType: v.optional(v.string()),
    identificationNumber: v.optional(v.string()),
    verificationStatus: v.optional(verificationStatus),
    verificationIdType: v.optional(v.string()),
    verificationIdNumber: v.optional(v.string()),
    verificationIdDocument: v.optional(v.id("_storage")),
    verificationSelfie: v.optional(v.id("_storage")),
    verificationDateOfBirth: v.optional(v.string()),
    verificationAddress: v.optional(v.string()),
    verificationEmergencyName: v.optional(v.string()),
    verificationEmergencyPhone: v.optional(v.string()),
    verificationSubmittedAt: v.optional(v.number()),
    verificationProcessedAt: v.optional(v.number()),
    verificationDecision: v.optional(verificationDecision),
    verificationReason: v.optional(v.string()),
    verificationReviewedAt: v.optional(v.number()),
    verificationRejectionReason: v.optional(v.string()),
    verificationReviewerId: v.optional(v.id("users")),
    isOnline: v.optional(v.boolean()),
    role: v.union(v.literal("student"), v.literal("rider"), v.literal("admin")),
    walletBalance: v.number(),
    walletReserved: v.optional(v.number()),
    activeRideId: v.optional(v.id("rides")),
    ratingTotal: v.optional(v.number()),
    ratingCount: v.optional(v.number()),
    payoutBankName: v.optional(v.string()),
    payoutBankCode: v.optional(v.string()),
    payoutAccountNumber: v.optional(v.string()),
    payoutAccountName: v.optional(v.string()),
  })
    .index("email", ["email"])
    .index("verification_id_number", ["verificationIdNumber"])
    .index("by_role", ["role"]),
  userIdentityMappings: defineTable({
    subject: v.string(),
    userId: v.id("users"),
  }).index("by_subject", ["subject"]),
  locations: defineTable({
    slug: v.optional(v.string()),
    name: v.string(),
    group: v.optional(v.union(v.literal("backgate"), v.literal("frontgate"), v.literal("school-area"))),
    detail: v.string(),
    active: v.boolean(),
    city: v.optional(v.string()),
    latitude: v.optional(v.number()),
    longitude: v.optional(v.number()),
    lat: v.optional(v.number()),
    lng: v.optional(v.number()),
    countryCode: v.optional(v.string()),
    state: v.optional(v.string()),
  }).index("by_active", ["active"]).index("by_slug", ["slug"]),
  rides: defineTable({
    userId: v.id("users"),
    bookingReference: v.optional(v.string()),
    riderId: v.optional(v.id("users")),
    pickupLocationId: v.optional(v.id("locations")),
    destinationLocationId: v.optional(v.id("locations")),
    pickupLabel: v.optional(v.string()),
    destinationLabel: v.optional(v.string()),
    pickupCity: v.optional(v.string()),
    pickupState: v.optional(v.string()),
    destinationCity: v.optional(v.string()),
    destinationState: v.optional(v.string()),
    pickupLatitude: v.optional(v.number()),
    pickupLongitude: v.optional(v.number()),
    destinationLatitude: v.optional(v.number()),
    destinationLongitude: v.optional(v.number()),
    distance: v.optional(v.number()),
    estimatedFare: v.optional(v.number()),
    fare: v.optional(v.number()),
    offeredFare: v.optional(v.number()),
    agreedFare: v.optional(v.number()),
    proposedPrice: v.optional(v.number()),
    proposedBy: v.optional(v.id("users")),
    negotiationStartedAt: v.optional(v.number()),
    paymentStatus: v.optional(paymentStatus),
    status: rideStatus,
    requestStatus: v.optional(rideRequestStatus),
    requestedAt: v.number(),
    expiresAt: v.optional(v.number()),
    acceptedAt: v.optional(v.number()),
    cancelledAt: v.optional(v.number()),
    cancellationReason: v.optional(v.string()),
    completedAt: v.optional(v.number()),
    completionRequestedAt: v.optional(v.number()),
    completionConfirmedAt: v.optional(v.number()),
    completionConfirmedBy: v.optional(v.id("users")),
    ratingSubmittedAt: v.optional(v.number()),
    disputeReportedAt: v.optional(v.number()),
    disputeReportedBy: v.optional(v.id("users")),
    disputeReason: v.optional(v.string()),
  })
    .index("by_user", ["userId"])
    .index("by_booking_reference", ["bookingReference"])
    .index("by_status", ["status"])
    .index("by_rider", ["riderId"]),
  declinedRides: defineTable({
    riderId: v.id("users"),
    rideId: v.id("rides"),
    createdAt: v.number(),
  }).index("by_rider", ["riderId"]),
  rideOffers: defineTable({
    rideId: v.id("rides"),
    riderId: v.id("users"),
    fare: v.number(),
    currency: v.literal("NGN"),
    status: rideOfferStatus,
    createdAt: v.number(),
    updatedAt: v.optional(v.number()),
  })
    .index("by_ride", ["rideId"])
    .index("by_rider", ["riderId"])
    .index("by_ride_rider", ["rideId", "riderId"]),
  notifications: defineTable({
    userId: v.id("users"),
    type: v.union(
      v.literal("ride_request"),
      v.literal("ride_offer"),
      v.literal("offer_accepted"),
      v.literal("offer_closed"),
      v.literal("ride_cancelled"),
      v.literal("ride_expired"),
      v.literal("payment_confirmed"),
      v.literal("ride_status"),
    ),
    title: v.string(),
    body: v.string(),
    rideId: v.optional(v.id("rides")),
    offerId: v.optional(v.id("rideOffers")),
    destination: v.string(),
    createdAt: v.number(),
    readAt: v.optional(v.number()),
  })
    .index("by_user_created", ["userId", "createdAt"])
    .index("by_user_unread", ["userId", "readAt"]),
  rideRatings: defineTable({
    rideId: v.id("rides"),
    customerId: v.id("users"),
    riderId: v.id("users"),
    stars: v.number(),
    comment: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_ride", ["rideId"]).index("by_rider", ["riderId"]).index("by_customer", ["customerId"]),
  payments: defineTable({
    rideId: v.id("rides"),
    studentId: v.id("users"),
    riderId: v.optional(v.id("users")),
    amount: v.number(),
    currency: v.literal("NGN"),
    paystackReference: v.string(),
    status: paymentStatus,
    method: v.optional(v.union(v.literal("paystack"), v.literal("wallet"))),
    ledgerStatus: v.optional(v.union(v.literal("held"), v.literal("released"), v.literal("refunded"))),
    paymentStage: v.optional(paymentStage),
    studentWalletTransactionReference: v.optional(v.string()),
    cancellationFeeAmount: v.optional(v.number()),
    refundedAmount: v.optional(v.number()),
    cancelledAt: v.optional(v.number()),
    completionAt: v.optional(v.number()),
    releaseAt: v.optional(v.number()),
    payoutStatus: v.optional(payoutStatus),
    createdAt: v.number(),
    paidAt: v.optional(v.number()),
    verificationAt: v.optional(v.number()),
    failureReason: v.optional(v.string()),
    authorizationUrl: v.optional(v.string()),
  }).index("by_ride", ["rideId"]).index("by_reference", ["paystackReference"]).index("by_created_at", ["createdAt"]),
  paymentRefunds: defineTable({
    paymentId: v.id("payments"),
    rideId: v.id("rides"),
    studentId: v.id("users"),
    amount: v.number(),
    currency: v.literal("NGN"),
    transactionReference: v.string(),
    status: v.union(
      v.literal("pending"),
      v.literal("processing"),
      v.literal("submitted"),
      v.literal("completed"),
      v.literal("review"),
    ),
    createdAt: v.number(),
    submittedAt: v.optional(v.number()),
    completedAt: v.optional(v.number()),
    providerRefundId: v.optional(v.string()),
    reviewReason: v.optional(v.string()),
  })
    .index("by_payment", ["paymentId"])
    .index("by_transaction_reference", ["transactionReference"])
    .index("by_status", ["status"]),
  riderEarnings: defineTable({
    riderId: v.id("users"),
    rideId: v.id("rides"),
    paymentId: v.id("payments"),
    grossFare: v.number(),
    platformFee: v.number(),
    riderEarnings: v.number(),
    currency: v.literal("NGN"),
    status: earningsStatus,
    createdAt: v.number(),
    completedAt: v.number(),
  }).index("by_rider", ["riderId"]).index("by_ride", ["rideId"]).index("by_status", ["status"]),
  payouts: defineTable({
    riderId: v.id("users"),
    rideId: v.id("rides"),
    paymentId: v.id("payments"),
    earningsId: v.id("riderEarnings"),
    amount: v.number(),
    currency: v.literal("NGN"),
    status: payoutStatus,
    reference: v.string(),
    createdAt: v.number(),
    processedAt: v.optional(v.number()),
    failureReason: v.optional(v.string()),
    requestedAt: v.optional(v.number()),
    requestedBy: v.optional(v.id("users")),
    approvedAt: v.optional(v.number()),
    approvedBy: v.optional(v.id("users")),
    rejectedAt: v.optional(v.number()),
    rejectedBy: v.optional(v.id("users")),
    rejectionReason: v.optional(v.string()),
    paidBy: v.optional(v.id("users")),
    provider: v.optional(v.string()),
    providerReference: v.optional(v.string()),
    lastAttemptAt: v.optional(v.number()),
    retryCount: v.optional(v.number()),
    reviewReason: v.optional(v.string()),
    payoutMethod: v.optional(v.string()),
    payoutNotes: v.optional(v.string()),
    bankName: v.optional(v.string()),
    accountNumber: v.optional(v.string()),
    accountName: v.optional(v.string()),
  }).index("by_rider", ["riderId"]).index("by_ride", ["rideId"]).index("by_status", ["status"]).index("by_reference", ["reference"]),
  auditEvents: defineTable({
    category: v.union(v.literal("verification"), v.literal("financial"), v.literal("ride")),
    action: v.string(),
    status: v.string(),
    actorId: v.optional(v.id("users")),
    riderId: v.optional(v.id("users")),
    rideId: v.optional(v.id("rides")),
    paymentId: v.optional(v.id("payments")),
    payoutId: v.optional(v.id("payouts")),
    reason: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_created_at", ["createdAt"]).index("by_category", ["category"]),
  financialLedger: defineTable({
    kind: v.union(
      v.literal("wallet_funding"),
      v.literal("ride_payment"),
      v.literal("payment_pool_hold"),
      v.literal("rider_earnings"),
      v.literal("rider_payout"),
      v.literal("refund"),
      v.literal("cancellation_fee"),
    ),
    direction: v.union(v.literal("credit"), v.literal("debit")),
    userId: v.optional(v.id("users")),
    riderId: v.optional(v.id("users")),
    rideId: v.optional(v.id("rides")),
    paymentId: v.optional(v.id("payments")),
    payoutId: v.optional(v.id("payouts")),
    amount: v.number(),
    currency: v.literal("NGN"),
    reference: v.string(),
    status: v.string(),
    createdAt: v.number(),
  }).index("by_kind", ["kind"]).index("by_payment", ["paymentId"]).index("by_reference", ["reference"]).index("by_created_at", ["createdAt"]),
  walletTransactions: defineTable({
    userId: v.id("users"),
    amount: v.number(),
    type: v.union(
      v.literal("ride_charge"),
      v.literal("top_up"),
      v.literal("ride_earning"),
      v.literal("withdrawal"),
      v.literal("ride_refund"),
      v.literal("cancellation_fee"),
    ),
    description: v.string(),
    rideId: v.optional(v.id("rides")),
      status: v.optional(v.union(v.literal("pending"), v.literal("processing"), v.literal("paid"), v.literal("failed"), v.literal("completed"))),
      currency: v.optional(v.literal("NGN")),
    createdAt: v.number(),
    provider: v.optional(v.string()),
    providerReference: v.optional(v.string()),
  }).index("by_user", ["userId"]).index("by_provider_reference", ["providerReference"]),
  walletFundingRequests: defineTable({
    userId: v.id("users"),
    amount: v.number(),
    currency: v.optional(v.literal("NGN")),
    status: v.union(
      v.literal("pending"),
      v.literal("verified"),
      v.literal("failed"),
    ),
    provider: v.string(),
    createdAt: v.number(),
    providerReference: v.optional(v.string()),
    authorizationUrl: v.optional(v.string()),
    paidAt: v.optional(v.number()),
    verificationAt: v.optional(v.number()),
    failureReason: v.optional(v.string()),
  }).index("by_user", ["userId"]).index("by_provider_reference", ["providerReference"]).index("by_created_at", ["createdAt"]),
  withdrawals: defineTable({
    userId: v.id("users"),
    amount: v.number(),
    currency: v.literal("NGN"),
    bankName: v.string(),
    accountNumber: v.string(),
    accountName: v.string(),
    status: withdrawalStatus,
    provider: v.literal("not_configured"),
    reference: v.string(),
    createdAt: v.number(),
    processedAt: v.optional(v.number()),
    failureReason: v.optional(v.string()),
  }).index("by_user", ["userId"]).index("by_status", ["status"]).index("by_reference", ["reference"]).index("by_created_at", ["createdAt"]),
});
